-- =====================================================================
-- Ayojon — V1: core schema (tables, keys, constraints, indexes)
--
-- Target: PostgreSQL 15+ (Supabase). Managed by Flyway — never edit an
-- applied migration; add a new V<n>__description.sql instead.
--
-- Conventions
--   * Surrogate keys are BIGINT identity columns named <table>_id.
--   * Every timestamp is TIMESTAMPTZ (stored in UTC, displayed in Asia/Dhaka).
--   * Status / type vocabularies are VARCHAR + CHECK so they map cleanly to
--     Java enums via @Enumerated(EnumType.STRING).
--   * Derived facts (is_verified, min price, trending score, ...) are NOT
--     stored; they are computed in views (V3). The only deliberate cache is
--     users.points, which is maintained by a trigger (V2).
--
-- Feature map (F-numbers from the sprint guide) is noted per table.
-- =====================================================================


-- ---------------------------------------------------------------------
-- Users & lookups
-- ---------------------------------------------------------------------

-- All accounts. role decides what a user may do (USER / ORGANIZER / ADMIN).
CREATE TABLE users (
    user_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(255) NOT NULL,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role          VARCHAR(20)  NOT NULL DEFAULT 'USER'
                  CHECK (role IN ('USER', 'ORGANIZER', 'ADMIN')),
    points        INT          NOT NULL DEFAULT 0 CHECK (points >= 0),   -- F3 cache = SUM(attendance.points_awarded)
    avatar_url    TEXT,
    is_active     BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CHECK (email LIKE '%_@_%')
);
CREATE UNIQUE INDEX ux_users_email_lower ON users (lower(email));
CREATE INDEX ix_users_points ON users (points DESC) WHERE is_active;          -- F3 leaderboard

-- F5 / F16 primary category of an event (Music, Tech, Food, ...).
CREATE TABLE event_category (
    category_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(100) NOT NULL UNIQUE,
    description   TEXT
);

-- F16 free-form tags; an event can have many (see event_tag).
CREATE TABLE tag (
    tag_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tag_name VARCHAR(60) NOT NULL UNIQUE
);

-- F5 / F20 neighbourhoods of the city (Gulshan, Dhanmondi, ...).
-- Optional centre point is used to label heat-map clusters.
CREATE TABLE area (
    area_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area_name VARCHAR(100) NOT NULL UNIQUE,
    city      VARCHAR(100) NOT NULL DEFAULT 'Dhaka',
    latitude  NUMERIC(10, 7) CHECK (latitude  BETWEEN -90  AND 90),
    longitude NUMERIC(10, 7) CHECK (longitude BETWEEN -180 AND 180)
);

-- F1 / F2 / F6 physical places with coordinates.
CREATE TABLE venue (
    venue_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area_id       BIGINT NOT NULL REFERENCES area (area_id) ON DELETE RESTRICT,
    venue_name    VARCHAR(255) NOT NULL,
    venue_address TEXT NOT NULL,
    latitude      NUMERIC(10, 7) NOT NULL CHECK (latitude  BETWEEN -90  AND 90),
    longitude     NUMERIC(10, 7) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (venue_name, venue_address)
);
CREATE INDEX ix_venue_area ON venue (area_id);
CREATE INDEX ix_venue_lat_lng ON venue (latitude, longitude);                 -- F1 bounding-box pre-filter


-- ---------------------------------------------------------------------
-- Events
-- ---------------------------------------------------------------------

-- F16 submission, F17 edit/cancel, F18 approval lifecycle.
--   DRAFT -> PENDING_REVIEW -> PUBLISHED | REJECTED | REVISION_REQUESTED
--   REVISION_REQUESTED -> PENDING_REVIEW (organizer resubmits)
--   PUBLISHED -> CANCELLED
-- "Completed" is not a status: an event is over when end_time < now().
CREATE TABLE event (
    event_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizer_id        BIGINT NOT NULL REFERENCES users (user_id) ON DELETE RESTRICT,
    category_id         BIGINT NOT NULL REFERENCES event_category (category_id) ON DELETE RESTRICT,
    venue_id            BIGINT NOT NULL REFERENCES venue (venue_id) ON DELETE RESTRICT,
    title               VARCHAR(255) NOT NULL CHECK (btrim(title) <> ''),
    description         TEXT,
    start_time          TIMESTAMPTZ NOT NULL,
    end_time            TIMESTAMPTZ NOT NULL,
    ticket_url          TEXT,                               -- F16 official checkout link
    official_source_url TEXT,                               -- F6 organizer source / F7 evidence
    status              VARCHAR(30) NOT NULL DEFAULT 'PENDING_REVIEW'
                        CHECK (status IN ('DRAFT', 'PENDING_REVIEW', 'REVISION_REQUESTED',
                                          'PUBLISHED', 'REJECTED', 'CANCELLED')),
    cancellation_reason TEXT,
    check_in_points     INT NOT NULL DEFAULT 10 CHECK (check_in_points >= 0),   -- F3
    published_at        TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by          BIGINT REFERENCES users (user_id) ON DELETE SET NULL,  -- who made the last edit (feeds F17 audit trigger)
    search_vector       TSVECTOR GENERATED ALWAYS AS (
                            setweight(to_tsvector('english', coalesce(title, '')), 'A') ||
                            setweight(to_tsvector('english', coalesce(description, '')), 'B')
                        ) STORED,                                                -- F5 keyword search
    CHECK (end_time > start_time),
    CHECK (status <> 'CANCELLED' OR cancellation_reason IS NOT NULL)
);
CREATE INDEX ix_event_status_start ON event (status, start_time);
CREATE INDEX ix_event_organizer    ON event (organizer_id, created_at DESC);  -- F18 organizer status page
CREATE INDEX ix_event_category     ON event (category_id);
CREATE INDEX ix_event_venue_time   ON event (venue_id, start_time);           -- F11 overlap detection
CREATE INDEX ix_event_search       ON event USING GIN (search_vector);

CREATE TABLE event_tag (
    event_id BIGINT NOT NULL REFERENCES event (event_id) ON DELETE CASCADE,
    tag_id   BIGINT NOT NULL REFERENCES tag (tag_id) ON DELETE CASCADE,
    PRIMARY KEY (event_id, tag_id)
);
CREATE INDEX ix_event_tag_tag ON event_tag (tag_id);

-- F16 posters / gallery. At most one POSTER per event.
CREATE TABLE event_media (
    media_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id    BIGINT NOT NULL REFERENCES event (event_id) ON DELETE CASCADE,
    media_url   TEXT NOT NULL,
    media_type  VARCHAR(20) NOT NULL DEFAULT 'IMAGE'
                CHECK (media_type IN ('POSTER', 'IMAGE', 'VIDEO')),
    sort_order  INT NOT NULL DEFAULT 0,
    uploaded_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_event_media_event ON event_media (event_id, sort_order);
CREATE UNIQUE INDEX ux_event_media_one_poster ON event_media (event_id) WHERE media_type = 'POSTER';

-- F5 / F6 ticket cost tiers. A free event has a single tier priced 0.
CREATE TABLE ticket_tier (
    tier_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id    BIGINT NOT NULL REFERENCES event (event_id) ON DELETE CASCADE,
    tier_name   VARCHAR(100) NOT NULL,
    price       NUMERIC(10, 2) NOT NULL CHECK (price >= 0),
    currency    CHAR(3) NOT NULL DEFAULT 'BDT',
    description TEXT,
    UNIQUE (event_id, tier_name)
);
CREATE INDEX ix_ticket_tier_event_price ON ticket_tier (event_id, price);


-- ---------------------------------------------------------------------
-- Admin moderation
-- ---------------------------------------------------------------------

-- F18 admin decisions on submissions. Inserting a row moves the event's
-- status (trigger in V2) and notifies the organizer.
CREATE TABLE event_submission_review (
    review_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id    BIGINT NOT NULL REFERENCES event (event_id) ON DELETE CASCADE,
    admin_id    BIGINT REFERENCES users (user_id) ON DELETE SET NULL,
    decision    VARCHAR(30) NOT NULL
                CHECK (decision IN ('APPROVED', 'REJECTED', 'REVISION_REQUESTED')),
    comment     TEXT,
    reviewed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (decision = 'APPROVED' OR comment IS NOT NULL)          -- rejections must explain why
);
CREATE INDEX ix_submission_review_event ON event_submission_review (event_id, reviewed_at DESC);

-- F7 legitimacy checks against official sources. The latest row per event
-- decides the "Verified" badge (view v_event_verification_status).
CREATE TABLE event_verification (
    verification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id        BIGINT NOT NULL REFERENCES event (event_id) ON DELETE CASCADE,
    admin_id        BIGINT REFERENCES users (user_id) ON DELETE SET NULL,
    decision        VARCHAR(20) NOT NULL CHECK (decision IN ('VERIFIED', 'REJECTED', 'REVOKED')),
    source_url      TEXT,
    notes           TEXT,
    verified_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_event_verification_event ON event_verification (event_id, verified_at DESC);

-- F17 public audit trail. Rows are written automatically by a trigger on
-- event UPDATE (one row per changed field); apps may add NOTE rows.
CREATE TABLE event_change_log (
    change_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id    BIGINT NOT NULL REFERENCES event (event_id) ON DELETE CASCADE,
    changed_by  BIGINT REFERENCES users (user_id) ON DELETE SET NULL,
    change_type VARCHAR(30) NOT NULL
                CHECK (change_type IN ('RESCHEDULED', 'VENUE_CHANGED', 'DETAILS_UPDATED',
                                       'STATUS_CHANGED', 'CANCELLED', 'NOTE')),
    field_name  VARCHAR(50),
    old_value   TEXT,
    new_value   TEXT,
    note        TEXT,
    changed_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_event_change_log_event ON event_change_log (event_id, changed_at DESC);

-- F14 dispute / fraud reports.
CREATE TABLE dispute_reason (
    reason_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reason_code VARCHAR(40)  NOT NULL UNIQUE,     -- SPAM, COUNTERFEIT_LISTING, ...
    reason_name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE dispute_report (
    report_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id     BIGINT NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    event_id        BIGINT NOT NULL REFERENCES event (event_id) ON DELETE CASCADE,
    reason_id       BIGINT NOT NULL REFERENCES dispute_reason (reason_id) ON DELETE RESTRICT,
    details         TEXT NOT NULL CHECK (length(details) BETWEEN 10 AND 2000),
    evidence_url    TEXT,
    status          VARCHAR(20) NOT NULL DEFAULT 'PENDING'
                    CHECK (status IN ('PENDING', 'UNDER_REVIEW', 'RESOLVED', 'DISMISSED')),
    resolved_by     BIGINT REFERENCES users (user_id) ON DELETE SET NULL,
    resolution_note TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved_at     TIMESTAMPTZ,
    CHECK ((status IN ('RESOLVED', 'DISMISSED')) = (resolved_at IS NOT NULL))
);
CREATE INDEX ix_dispute_report_queue ON dispute_report (status, created_at);
CREATE INDEX ix_dispute_report_event ON dispute_report (event_id);
-- one open report per user / event / reason (stops spam-reporting)
CREATE UNIQUE INDEX ux_dispute_report_open
    ON dispute_report (reporter_id, event_id, reason_id)
    WHERE status IN ('PENDING', 'UNDER_REVIEW');


-- ---------------------------------------------------------------------
-- User activity
-- ---------------------------------------------------------------------

-- F2 / F3 / F20 check-ins. points_awarded is filled by trigger (V2):
-- the event's check_in_points if the event is verified, otherwise 0.
CREATE TABLE attendance (
    attendance_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    event_id       BIGINT NOT NULL REFERENCES event (event_id) ON DELETE CASCADE,
    checked_in_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    points_awarded INT NOT NULL DEFAULT 0 CHECK (points_awarded >= 0),
    UNIQUE (user_id, event_id)
);
CREATE INDEX ix_attendance_event ON attendance (event_id);
CREATE INDEX ix_attendance_user_time ON attendance (user_id, checked_in_at DESC);

-- F3 milestone badges.
CREATE TABLE badge (
    badge_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    badge_name       VARCHAR(100) NOT NULL UNIQUE,
    description      TEXT,
    milestone_points INT NOT NULL UNIQUE CHECK (milestone_points > 0),
    icon_url         TEXT
);

CREATE TABLE user_badge (
    user_id   BIGINT NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    badge_id  BIGINT NOT NULL REFERENCES badge (badge_id) ON DELETE CASCADE,
    earned_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, badge_id)
);
CREATE INDEX ix_user_badge_badge ON user_badge (badge_id);

-- F8 / F9 / F19 "saved" events. One row per user+event; bookmarked_at
-- drives the weekly trending ranking.
CREATE TABLE bookmark (
    user_id       BIGINT NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    event_id      BIGINT NOT NULL REFERENCES event (event_id) ON DELETE CASCADE,
    bookmarked_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, event_id)
);
CREATE INDEX ix_bookmark_event_time ON bookmark (event_id, bookmarked_at);
CREATE INDEX ix_bookmark_time ON bookmark (bookmarked_at);

-- F9 custom collections and private wishlists of saved events.
CREATE TABLE collection (
    collection_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    collection_name VARCHAR(150) NOT NULL,
    description     TEXT,
    collection_type VARCHAR(20) NOT NULL DEFAULT 'COLLECTION'
                    CHECK (collection_type IN ('COLLECTION', 'WISHLIST')),
    is_private      BOOLEAN NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, collection_name),
    UNIQUE (collection_id, user_id)            -- target of collection_item composite FK
);

-- Items must be the owner's own bookmarks: the composite FKs guarantee that
-- the collection and the bookmark belong to the same user. A trigger (V2)
-- fills user_id from the collection and auto-creates the bookmark.
CREATE TABLE collection_item (
    collection_id BIGINT NOT NULL,
    event_id      BIGINT NOT NULL,
    user_id       BIGINT NOT NULL,
    note          TEXT,
    added_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (collection_id, event_id),
    FOREIGN KEY (collection_id, user_id) REFERENCES collection (collection_id, user_id) ON DELETE CASCADE,
    FOREIGN KEY (user_id, event_id)      REFERENCES bookmark (user_id, event_id)        ON DELETE CASCADE
);
CREATE INDEX ix_collection_item_bookmark ON collection_item (user_id, event_id);

-- F10 weekend schedule built from saved events; F11 conflicts and F13
-- calendar export are derived from it (views in V3).
CREATE TABLE itinerary (
    itinerary_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    title        VARCHAR(150) NOT NULL,
    start_date   DATE NOT NULL,
    end_date     DATE NOT NULL,
    notes        TEXT,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (end_date >= start_date AND end_date - start_date <= 6)
);
CREATE INDEX ix_itinerary_user ON itinerary (user_id, start_date);

-- planned_start/planned_end are optional overrides when the user only plans
-- to attend part of an event; otherwise the event's own times are used.
CREATE TABLE itinerary_item (
    itinerary_id  BIGINT NOT NULL REFERENCES itinerary (itinerary_id) ON DELETE CASCADE,
    event_id      BIGINT NOT NULL REFERENCES event (event_id) ON DELETE CASCADE,
    planned_start TIMESTAMPTZ,
    planned_end   TIMESTAMPTZ,
    note          TEXT,
    added_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (itinerary_id, event_id),
    CHECK (planned_start IS NULL OR planned_end IS NULL OR planned_end > planned_start)
);
CREATE INDEX ix_itinerary_item_event ON itinerary_item (event_id);

-- F15 ratings & short reviews. The FK to attendance means only users who
-- actually checked in can review — enforced by the database itself.
CREATE TABLE review (
    review_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL,
    event_id    BIGINT NOT NULL,
    rating      SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    review_text VARCHAR(1000),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, event_id),
    FOREIGN KEY (user_id, event_id) REFERENCES attendance (user_id, event_id) ON DELETE CASCADE
);
CREATE INDEX ix_review_event ON review (event_id, created_at DESC);

-- F12 follow an event to get change notifications.
CREATE TABLE event_follow (
    user_id     BIGINT NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    event_id    BIGINT NOT NULL REFERENCES event (event_id) ON DELETE CASCADE,
    followed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, event_id)
);
CREATE INDEX ix_event_follow_event ON event_follow (event_id);

-- F12 / F18 / F3 in-app notifications (written by triggers and by the app).
CREATE TABLE notification (
    notification_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    event_id          BIGINT REFERENCES event (event_id) ON DELETE SET NULL,
    notification_type VARCHAR(30) NOT NULL DEFAULT 'GENERAL'
                      CHECK (notification_type IN ('EVENT_UPDATED', 'EVENT_CANCELLED', 'SUBMISSION_STATUS',
                                                   'EVENT_VERIFIED', 'BADGE_EARNED', 'REPORT_UPDATE', 'GENERAL')),
    message           TEXT NOT NULL,
    is_read           BOOLEAN NOT NULL DEFAULT FALSE,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_notification_inbox ON notification (user_id, is_read, created_at DESC);


-- ---------------------------------------------------------------------
-- Sponsors & vouchers (F4)
-- ---------------------------------------------------------------------

CREATE TABLE sponsor (
    sponsor_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sponsor_name  VARCHAR(150) NOT NULL UNIQUE,
    website_url   TEXT,
    logo_url      TEXT,
    contact_email VARCHAR(255),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- An ad campaign run by a sponsor; vouchers are generated from campaigns.
CREATE TABLE ad_campaign (
    campaign_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sponsor_id    BIGINT NOT NULL REFERENCES sponsor (sponsor_id) ON DELETE CASCADE,
    campaign_name VARCHAR(150) NOT NULL,
    description   TEXT,
    banner_url    TEXT,
    target_url    TEXT,                       -- third-party booking site
    starts_at     TIMESTAMPTZ NOT NULL,
    ends_at       TIMESTAMPTZ NOT NULL,
    is_active     BOOLEAN NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (ends_at > starts_at)
);
CREATE INDEX ix_ad_campaign_sponsor ON ad_campaign (sponsor_id);

CREATE TABLE voucher (
    voucher_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id         BIGINT NOT NULL REFERENCES ad_campaign (campaign_id) ON DELETE CASCADE,
    event_id            BIGINT REFERENCES event (event_id) ON DELETE SET NULL,  -- NULL = any booking on the partner site
    promo_code          VARCHAR(50) NOT NULL UNIQUE CHECK (promo_code = upper(promo_code)),
    description         TEXT,
    discount_percent    NUMERIC(5, 2) NOT NULL CHECK (discount_percent > 0 AND discount_percent <= 100),
    max_discount_amount NUMERIC(10, 2) CHECK (max_discount_amount > 0),
    min_points_required INT NOT NULL DEFAULT 0 CHECK (min_points_required >= 0),  -- ties rewards to F3 points
    total_quantity      INT CHECK (total_quantity > 0),                           -- NULL = unlimited
    booking_url         TEXT,
    valid_from          TIMESTAMPTZ NOT NULL DEFAULT now(),
    valid_until         TIMESTAMPTZ NOT NULL,
    is_active           BOOLEAN NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (valid_until > valid_from)
);
CREATE INDEX ix_voucher_campaign ON voucher (campaign_id);
CREATE INDEX ix_voucher_valid ON voucher (valid_until) WHERE is_active;

CREATE TABLE voucher_claim (
    claim_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    voucher_id  BIGINT NOT NULL REFERENCES voucher (voucher_id) ON DELETE CASCADE,
    claimed_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    redeemed_at TIMESTAMPTZ,
    UNIQUE (user_id, voucher_id),
    CHECK (redeemed_at IS NULL OR redeemed_at >= claimed_at)
);
CREATE INDEX ix_voucher_claim_voucher ON voucher_claim (voucher_id);
